#!/usr/bin/env node
/* =========================================================
   npm run build:manifest
   Scans /files/<category>/* and regenerates js/manifest.js.
   Descriptions and tags you already wrote are kept.
   ========================================================= */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const FILES = path.join(ROOT, 'files');
const OUT = path.join(ROOT, 'js', 'manifest.js');

const KNOWN = ['photos', 'videos', 'docs', 'apk', 'audio', 'archives', 'code', 'other'];
const EXT2CAT = {};
const MAP = {
  photos: 'jpg jpeg png webp gif bmp avif heic heif svg tif tiff ico raw dng cr2 nef'.split(' '),
  videos: 'mp4 m4v mov mkv webm avi wmv flv mpg mpeg 3gp'.split(' '),
  docs: 'pdf doc docx xls xlsx ppt pptx odt ods odp rtf txt md markdown csv tsv json xml yaml yml log ini epub'.split(' '),
  apk: 'apk xapk apks aab ipa'.split(' '),
  audio: 'mp3 m4a aac wav flac ogg oga opus amr aiff mid wma'.split(' '),
  archives: 'zip rar 7z tar gz tgz bz2 xz zst iso img cab jar'.split(' '),
  code: 'js mjs cjs ts tsx jsx html htm css scss py rb go rs java kt swift c h cpp php pl lua sh bash zsh sql dart vue svelte toml env'.split(' ')
};
Object.keys(MAP).forEach((c) => MAP[c].forEach((e) => (EXT2CAT[e] = c)));

function readExisting() {
  if (!fs.existsSync(OUT)) return new Map();
  const src = fs.readFileSync(OUT, 'utf8');

/* Reads the array literal assigned to window.CLOUD_MANIFEST, ignoring the
   commented-out examples in the file header. */
function extractArray(fileSrc) {
  const noBlock = fileSrc.replace(/\/\*[\s\S]*?\*\//g, '');
  const lines = noBlock.split('\n').filter((l) => !/^\s*\/\//.test(l));
  const src = lines.join('\n');
  const m = src.match(/window\.CLOUD_MANIFEST\s*=\s*(\[[\s\S]*?\]);/);
  return m ? m[1] : null;
}

  const literal = extractArray(src);
  if (!literal) return new Map();
  let arr = [];
  try {
    arr = JSON.parse(literal.replace(/,(\s*[}\]])/g, '$1'));
  } catch (e) {
    console.warn('  ! existing manifest not machine-readable, starting fresh');
    return new Map();
  }
  const map = new Map();
  (Array.isArray(arr) ? arr : []).forEach((r) => { if (r && r.path) map.set(r.path, r); });
  return map;
}

function walk(dir, base = '') {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    if (name.startsWith('.') || name === 'node_modules') continue;
    const full = path.join(dir, name);
    const st = fs.statSync(full);
    if (st.isDirectory()) out.push(...walk(full, path.join(base, name)));
    else out.push({ rel: path.join(base, name).split(path.sep).join('/'), full, st });
  }
  return out;
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const existing = readExisting();
const found = walk(FILES);

const rows = [];
for (const f of found) {
  if (f.st.size === 0) continue;
  const ext = (path.extname(f.rel) || '').slice(1).toLowerCase();
  const folder = f.rel.split('/')[0] || 'other';
  const category = KNOWN.includes(folder) ? folder : (EXT2CAT[ext] || 'other');
  const relPath = 'files/' + f.rel;
  const prev = existing.get(relPath) || {};
  rows.push({
    id: prev.id || slug(category + '-' + path.basename(f.rel, '.' + ext)),
    name: path.basename(f.rel),
    category,
    path: relPath,
    size: f.st.size,
    modified: prev.modified || f.st.mtime.toISOString().slice(0, 10),
    ...(prev.description ? { description: prev.description } : {}),
    ...(prev.tags && prev.tags.length ? { tags: prev.tags } : {}),
    ...(prev.starred ? { starred: true } : {})
  });
}

rows.sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));

const header = `/* =========================================================
   Nendu Cloud · js/manifest.js
   The published library of this drive — files that live in the
   repository under /files/<category>/<name>, served by GitHub
   Pages next to the site. Regenerated by \`npm run build:manifest\`.

   Local drag & drop uploads never appear here on purpose: they
   stay inside this browser's IndexedDB.
   ========================================================= */`;

const body = JSON.stringify(rows, null, 2).replace(/\n    "/g, '\n    "');
fs.writeFileSync(OUT, `${header}\n\nwindow.CLOUD_MANIFEST = ${body};\n`);

const tally = {};
rows.forEach((r) => (tally[r.category] = (tally[r.category] || 0) + 1));
const total = rows.reduce((a, r) => a + r.size, 0);
console.log(`✔ js/manifest.js rebuilt — ${rows.length} file(s), ${(total / 1048576).toFixed(2)} MB`);
Object.keys(tally).sort().forEach((c) => console.log(`   ${c.padEnd(9)} ${tally[c]}`));
if (!rows.length) console.log('   (files/ is empty — the drive starts clean, drag & drop to add locally)');
